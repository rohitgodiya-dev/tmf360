-- Part 15 — study / country / site hierarchy for enterprise scale (docs/enterprise-plan-review.md) (ENT-01..04)
--
-- Builds on Part 2b–2d (study_countries, study_sites, parties, contact_roles, milestones); nothing is duplicated:
--   * countries              ISO 3166-1 reference (name, UN region, clinical-trial regulator); read-only, changed by migration
--   * parties                site institution details: city, address, institution_type (sites are parties, never Site360 "sites")
--   * study_sites            enrollment target and actual
--   * milestone types        first patient in per country and per site (regulatory and activation dates are already milestones)
--   * study_country_summary  per-country rollup (sites, active sites, enrollment), RLS of the caller applies
--   * structure_completeness per-scope Final / total counts from navigator_items (PLC-06), RLS of the caller applies
--   * indexes for 10–20 studies × 20–40 sites per organisation

------------------------------------------------------------------------------
-- 1. Countries reference
------------------------------------------------------------------------------
create table if not exists countries (
  code text primary key check (code ~ '^[A-Z]{2}$'),
  name text not null,
  region text not null check (region in ('Africa', 'Americas', 'Asia', 'Europe', 'Oceania', 'Antarctica')),
  regulatory_authority text
);
alter table countries enable row level security;
drop policy if exists "countries readable" on countries;
create policy "countries readable" on countries for select to authenticated using (true);
revoke insert, update, delete, truncate on countries from anon, authenticated;

