------------------------------------------------------------------------------
-- 4. Rollup views (security invoker: each caller sees only what RLS lets them see)
------------------------------------------------------------------------------
drop view if exists study_country_summary;
create view study_country_summary with (security_invoker = true) as
select sc.org_id, sc.study_id, sc.id as study_country_id, sc.country_code, c.name as country_name, c.region,
       c.regulatory_authority, sc.status,
       count(ss.id)::int as sites_total,
       (count(ss.id) filter (where ss.status = 'ongoing'))::int as sites_active,
       coalesce(sum(ss.target_enrollment), 0)::int as target_enrollment,
       coalesce(sum(ss.actual_enrollment), 0)::int as actual_enrollment
from study_countries sc
join countries c on c.code = sc.country_code
left join study_sites ss on ss.study_country_id = sc.id
group by sc.id, c.code;

drop view if exists structure_completeness;
create view structure_completeness with (security_invoker = true) as
select org_id, study_code, study_country_id, study_site_id,
       (count(*) filter (where nav_status = 'Final'))::int as final_count,
       (count(*) filter (where nav_status = 'Missing'))::int as missing_count,
       count(*)::int as total_count
from navigator_items
where not is_historical
group by org_id, study_code, study_country_id, study_site_id;

revoke all on study_country_summary, structure_completeness from anon;
grant select on study_country_summary, structure_completeness to authenticated;

