// Generates the countries reference seed for the Part 15 migration (ISO 3166-1 alpha-2).
// Names come from i18n-iso-countries; region is the UN M49 continent; regulatory_authority is filled
// for the usual clinical-trial countries and left null elsewhere. Run: node scripts/generate-countries-migration.mjs
import countries from "i18n-iso-countries";
import en from "i18n-iso-countries/langs/en.json" with { type: "json" };

countries.registerLocale(en);

const REGIONS = {
  Africa: "DZ AO BJ BW BF BI CV CM CF TD KM CG CD CI DJ EG GQ ER SZ ET GA GM GH GN GW KE LS LR LY MG MW ML MR MU YT MA MZ NA NE NG RE RW SH ST SN SC SL SO ZA SS SD TZ TG TN UG EH ZM ZW IO TF",
  Americas: "AI AG AR AW BS BB BZ BM BO BQ BV BR CA KY CL CO CR CU CW DM DO EC SV FK GF GL GD GP GT GY HT HN JM MQ MX MS NI PA PY PE PR BL KN LC MF PM VC SX GS SR TT TC US UM UY VE VG VI",
  Asia: "AF AM AZ BH BD BT BN KH CN CY GE HK IN ID IR IQ IL JP JO KZ KW KG LA LB MO MY MV MN MM NP KP OM PK PS PH QA SA SG KR LK SY TW TJ TH TL TR TM AE UZ VN YE",
  Europe: "AX AL AD AT BY BE BA BG HR CZ DK EE FO FI FR DE GI GR GG VA HU IS IE IM IT JE LV LI LT LU MT MD MC ME NL MK NO PL PT RO RU SM RS SK SI ES SJ SE CH UA GB XK",
  Oceania: "AS AU CX CC CK FJ PF GU HM KI MH FM NR NC NZ NU NF MP PW PG PN WS SB TK TO TV VU WF",
  Antarctica: "AQ",
};

// National competent authorities for clinical trials. EU/EEA trials are submitted through CTIS.
const AUTHORITIES = {
  US: "FDA", CA: "Health Canada", MX: "COFEPRIS", BR: "ANVISA", AR: "ANMAT", CL: "ISP", CO: "INVIMA", PE: "INS",
  GB: "MHRA", CH: "Swissmedic", DE: "BfArM / PEI", FR: "ANSM", IT: "AIFA", ES: "AEMPS", NL: "CCMO / CBG-MEB",
  BE: "FAMHP", AT: "BASG", SE: "Swedish MPA", DK: "DKMA", NO: "DMP", FI: "Fimea", PL: "URPL", CZ: "SUKL",
  HU: "NNGYK", IE: "HPRA", PT: "INFARMED", GR: "EOF", RO: "ANMDMR", BG: "BDA", SK: "SUKL (SK)", SI: "JAZMP",
  HR: "HALMED", EE: "State Agency of Medicines", LV: "ZVA", LT: "VVKT", IS: "IMA", LU: "Ministry of Health (LU)",
  JP: "PMDA", CN: "NMPA", KR: "MFDS", TW: "TFDA", IN: "CDSCO", AU: "TGA", NZ: "Medsafe", SG: "HSA",
  ZA: "SAHPRA", IL: "Ministry of Health (IL)", TR: "TITCK", SA: "SFDA", EG: "EDA", AE: "MOHAP", TH: "Thai FDA",
  MY: "NPRA", PH: "FDA Philippines", HK: "Department of Health (HK)", VN: "DAV", UA: "State Expert Centre",
};

const regionOf = new Map(Object.entries(REGIONS).flatMap(([r, codes]) => codes.split(" ").map((c) => [c, r])));
// Shorter display names where the ISO official name is awkward in a table.
const DISPLAY = { US: "United States", TW: "Taiwan", CI: "Côte d'Ivoire", XK: "Kosovo" };
const names = { ...countries.getNames("en", { select: "official" }), ...DISPLAY };
const missing = Object.keys(names).filter((c) => !regionOf.has(c));
if (missing.length) throw new Error(`No region for: ${missing.join(", ")}`);
const unknown = [...regionOf.keys(), ...Object.keys(AUTHORITIES)].filter((c) => !names[c]);
if (unknown.length) throw new Error(`Not ISO codes: ${unknown.join(", ")}`);

const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const rows = Object.keys(names).sort().map((c) => `  (${q(c)}, ${q(names[c])}, ${q(regionOf.get(c))}, ${q(AUTHORITIES[c])})`);
console.log(`-- ${rows.length} countries (generated by scripts/generate-countries-migration.mjs)`);
console.log("insert into countries (code, name, region, regulatory_authority) values");
console.log(rows.join(",\n"));
console.log("on conflict (code) do update set name = excluded.name, region = excluded.region,\n  regulatory_authority = excluded.regulatory_authority;");
